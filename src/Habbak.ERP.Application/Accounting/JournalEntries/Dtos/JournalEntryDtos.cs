    public required long AccountId { get; init; }
    public required decimal DebitAmount { get; init; }
    public required decimal CreditAmount { get; init; }
    public required string CurrencyCode { get; init; }
    public required decimal ExchangeRate { get; init; }
    public required decimal BaseCurrencyDebitAmount { get; init; }
    public required decimal BaseCurrencyCreditAmount { get; init; }
    public string? Description { get; init; }

    /// <summary>CostCenterDimensionId -> CostCenterDimensionValueId.</summary>
